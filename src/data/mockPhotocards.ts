// ─── Helper pour mapper les types du JSON vers PhotocardType ─────────────────

const toType = (raw: string): PhotocardWithDetails["type"] => {
  const lower = raw.toLowerCase();
  if (lower.includes("pob")) return "pob";
  if (lower.includes("broadcast")) return "broadcast";
  if (lower.includes("lucky draw")) return "lucky_draw";
  if (lower.includes("event")) return "event";
  if (lower.includes("benefit")) return "benefit";
  return "normal";
};

